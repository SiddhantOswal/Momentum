export function predictRisk(order, conditions) {
  const orderParsed = PurchaseOrderSchema.safeParse(order);
  const conditionsParsed = ManufacturingConditionsSchema.safeParse(conditions);

  if (!orderParsed.success || !conditionsParsed.success) {
    return {
      ok: false,
      agent: "predictRisk",
      source: "mock-demo",
      message: "Order and conditions must both pass validation before risk prediction.",
      errors: [
        ...(orderParsed.success ? [] : orderParsed.error.issues.map((issue) => ({ field: issue.path.join(".") || "order", message: issue.message }))),
        ...(conditionsParsed.success ? [] : conditionsParsed.error.issues.map((issue) => ({ field: issue.path.join(".") || "conditions", message: issue.message }))),
      ],
    };
  }

  const humidityFactor = (conditionsParsed.data.ambientRhPct - 45) / 100;
  const moistureFactor = (conditionsParsed.data.paperMoisturePct - 8) / 100;
  const dimensionFactor = ((orderParsed.data.lengthMm * orderParsed.data.widthMm * orderParsed.data.heightMm) / 480000) - 1;

  const risk = {
    warp: toRiskNumber(clamp(7 + humidityFactor * 42 + moistureFactor * 36 + dimensionFactor * 18, 0, 98)),
    delamination: toRiskNumber(clamp(6 + moistureFactor * 45 + (orderParsed.data.inkCoveragePct || 0) * 0.22, 0, 96)),
    strengthFailure: toRiskNumber(clamp(5 + (orderParsed.data.ply || 1) * 6 + moistureFactor * 34, 0, 94)),
    printDefects: toRiskNumber(clamp(8 + ((orderParsed.data.inkCoveragePct || 0) - 40) * 0.28 + humidityFactor * 18, 0, 90)),
    creaseSlotCracks: toRiskNumber(clamp(4 + dimensionFactor * 26 + moistureFactor * 22 + humidityFactor * 12, 0, 88)),
  };

  const parsedRisk = RiskSchema.safeParse(risk);
  if (!parsedRisk.success) {
    return {
      ok: false,
      agent: "predictRisk",
      source: "mock-demo",
      message: "Generated risk values were invalid.",
      errors: parsedRisk.error.issues,
    };
  }

  return {
    ok: true,
    agent: "predictRisk",
    source: "mock-demo",
    model: "local-demo-risk-model",
    isRealModelPrediction: false,
    predictedRisks: parsedRisk.data,
    note: "These are mock defect-risk predictions for local development and demo evaluation only.",
  };
}

