import { ManufacturingConditionsSchema, PurchaseOrderSchema, RiskSchema } from "./schemas.js";

function clamp(value, min, max) {
  return Math.min(Math.max(value, min), max);
}

function toRiskNumber(value) {
  return Number(value.toFixed(1));
}

function parseWithSchema(schema, input, label) {
  const result = schema.safeParse(input);

  if (!result.success) {
    return {
      ok: false,
      label,
      errors: result.error.issues.map((issue) => ({
        field: issue.path.join(".") || "root",
        message: issue.message,
      })),
    };
  }

  return {
    ok: true,
    data: result.data,
  };
}

export function extractOrder(input) {
  const parsed = parseWithSchema(PurchaseOrderSchema, input, "order");

  if (!parsed.ok) {
    return {
      ok: false,
      agent: "extractOrder",
      source: "mock-demo",
      message: "Purchase order validation failed.",
      errors: parsed.errors,
    };
  }

  return {
    ok: true,
    agent: "extractOrder",
    source: "mock-demo",
    data: parsed.data,
    extractedAt: new Date().toISOString(),
    model: "local-order-extractor",
    isRealModelPrediction: false,
    note: "This result is generated by a local mock implementation and is not a production model output.",
  };
}

